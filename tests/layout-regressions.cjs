#!/usr/bin/env node
'use strict';
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..');
const html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
const css = fs.readFileSync(path.join(root, 'styles.css'), 'utf8');
const js = fs.readFileSync(path.join(root, 'blazarlab.js'), 'utf8');
const version = fs.readFileSync(path.join(root, 'VERSION'), 'utf8').trim();
assert.equal(version, '1.3.17');
assert.match(html, /A variabilidade conta <br\/>uma história/, 'título deve manter o espaço quando o br é oculto');
for (const label of ['Sample Entropy', 'Fisher–Shannon', 'MSE-WPE / CI']) assert.ok(html.includes(`class="method-name`) && html.includes(`>${label}</h3>`), `cartão deve destacar ${label}`);
assert.match(css, /\.site-nav\{display:flex;align-items:center;gap:5px;padding:6px;border:1px solid/);
assert.match(css, /\.nav-toggle\{display:none;width:44px;min-width:44px;height:44px;align-items:center;justify-content:center;flex-direction:column/);
assert.match(css, /\.abstract-list>\.abstract-card:last-child\{grid-column:1\/-1;width:min\(100%,calc\(\(100% - 13px\)\/2\)\);justify-self:center\}/, 'terceiro resumo deve ser centralizado como triângulo invertido');
assert.match(css, /\.abstract-card details summary,\.method-deep-dive summary\{min-height:48px/);
assert.match(js, /function isCompactViewport\(svgOrId\)/, 'responsividade deve medir o contêiner');
assert.match(js, /getBoundingClientRect\(\)\.width/, 'largura deve vir do elemento renderizado');
assert.match(js, /let compactWidth = Math\.max\(420, Math\.min\(width, Math\.round\(measured \|\| 420\)\)\)/, 'geometria compacta deve preservar espaço para rótulos');
assert.match(js, /const compactLabels = isCompactViewport\(svgId\)/, 'rótulos do perfil médio devem acompanhar a largura do gráfico');
assert.match(js, /compactLabels \? summary\.short\.split\('–'\)\[0\] : summary\.short/, 'bandas devem usar rótulos curtos em contêineres estreitos');
assert.match(js, /if \(!compactLabels\) content\.push\(`<text class="plot-label"/, 'valores sobre as barras devem ser omitidos no layout compacto');
assert.match(js, /const w=1020,h=720/, 'heatmap de SampEn deve ter linhas altas para toque');
assert.match(js, /responsiveRedrawSuppressed/, 'resize da tela cheia deve suprimir redesenho');
assert.match(js, /responsiveResizeSuppressionUntil/, 'ciclo de tela cheia deve ter período de estabilidade');
console.log('OK: hierarquia de métodos, menu, triângulo de artigos, alvos de toque e geometria responsiva.');
